import { createHash } from "node:crypto";
import { chmodSync, mkdirSync, readFileSync, rmSync, rmdirSync, statSync, utimesSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function formula(version: string, arm64: string, x64: string): string {
  if (!/^\d+\.\d+\.\d+$/.test(version) || ![arm64, x64].every(value => /^[a-f0-9]{64}$/.test(value))) {
    throw new Error("Invalid release version or SHA-256");
  }
  const base = `https://github.com/wenjun-xu/TokenFlow/releases/download/v${version}/tokenflow-${version}`;
  return `# Generated by scripts/prepare_release.ts; publish the matching binaries unchanged.
class Tokenflow < Formula
  desc "Local, read-only GitHub Copilot CLI token usage dashboard"
  homepage "https://github.com/wenjun-xu/TokenFlow"
  version "${version}"

  depends_on macos: :sonoma

  on_arm do
    url "${base}-darwin-arm64.tar.gz"
    sha256 "${arm64}"
  end

  on_intel do
    url "${base}-darwin-x64.tar.gz"
    sha256 "${x64}"
  end

  def install
    bin.install "tokenflow"
  end

  def caveats
    <<~EOS
      Run tokenflow start to open the local dashboard.
      Run tokenflow stop before upgrading or uninstalling.
      No Python, Node.js or Bun installation is needed.
      Requires working macOS sandbox-exec isolation; unsafe reads fail closed.
      Intel builds are experimental until verified on a native Intel Mac.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/tokenflow --version")
    assert_match "start", shell_output("#{bin}/tokenflow --help")
    with_env("HOME" => testpath.to_s) do
      shell_output("#{bin}/tokenflow start --db #{testpath}/missing.db --no-browser 2>&1", 1)
      refute_path_exists testpath/"missing.db"
    end
  end
end
`;
}

function command(args: string[], cwd = root, env: Record<string, string | undefined> = process.env): void {
  const result = Bun.spawnSync(args, { cwd, env, stdout: "inherit", stderr: "inherit" });
  if (result.exitCode !== 0) throw new Error(`Release command failed (${result.exitCode}): ${args[0]}`);
}

export function archiveBinary(binary: string, archive: string): string {
  chmodSync(binary, 0o755);
  utimesSync(binary, 0, 0);
  command(["/usr/bin/tar", "--format", "ustar", "--uid", "0", "--gid", "0",
    "--uname", "root", "--gname", "root", "-czf", resolve(archive),
    "-C", dirname(resolve(binary)), "tokenflow"], root, { ...process.env, COPYFILE_DISABLE: "1" });
  return createHash("sha256").update(readFileSync(archive)).digest("hex");
}

export function prepare(output: string, intelRuntime?: string): void {
  const metadata = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as { version: string };
  const version = metadata.version;
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error("Invalid package version");
  if (Bun.version !== "1.4.4") throw new Error("Release builds require Bun 1.4.4");
  if (process.platform !== "darwin") throw new Error("Build and sign releases on macOS");
  command([process.execPath, "build", "src/tool-summary.js", "--target=browser", "--minify", "--outfile", "web/tool-summary.js"]);
  output = resolve(output);
  mkdirSync(output, { recursive: true });
  const checksums: Record<string, string> = {};
  const artifacts: Array<{ name: string; sha256: string; bytes: number; executableBytes: number }> = [];
  for (const arch of ["arm64", "x64"] as const) {
    const staging = join(output, `stage-darwin-${arch}`);
    mkdirSync(staging, { recursive: true });
    const binary = join(staging, "tokenflow");
    const build = [
      process.execPath, "build", "--compile", "--minify",
      `--target=bun-darwin-${arch}`, "--no-compile-autoload-dotenv",
      "--no-compile-autoload-bunfig", "--no-compile-autoload-tsconfig",
      "--no-compile-autoload-package-json", "./src/cli.ts", "--outfile", binary,
    ];
    if (arch === "arm64" || intelRuntime) {
      build.push(`--compile-executable-path=${arch === "arm64" ? process.execPath : resolve(intelRuntime!)}`);
    }
    command(build);
    chmodSync(binary, 0o755);
    command(["/usr/bin/codesign", "--force", "--sign", "-", binary]);
    command(["/usr/bin/codesign", "--verify", "--strict", binary]);
    const name = `tokenflow-${version}-darwin-${arch}.tar.gz`;
    const archive = join(output, name);
    const sha256 = archiveBinary(binary, archive);
    checksums[arch] = sha256;
    artifacts.push({ name, sha256, bytes: statSync(archive).size, executableBytes: statSync(binary).size });
    rmSync(binary);
    rmdirSync(staging);
  }
  writeFileSync(join(output, "SHA256SUMS"), artifacts.map(item => `${item.sha256}  ${item.name}\n`).join(""));
  const tap = join(output, "homebrew-tap", "Formula");
  mkdirSync(tap, { recursive: true });
  writeFileSync(join(tap, "tokenflow.rb"), formula(version, checksums.arm64!, checksums.x64!));
  writeFileSync(join(output, "release-manifest.json"), JSON.stringify({
    version, bun: Bun.version, artifacts,
    note: "Cross-compilation does not establish native Intel compatibility.",
  }, null, 2) + "\n");
  console.log(JSON.stringify({ version, artifacts }, null, 2));
}

if (import.meta.main) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 2) throw new Error("Usage: bun scripts/prepare_release.ts [output-directory] [intel-bun-path]");
    prepare(args[0] ?? join(root, "dist"), args[1]);
  } catch (error) {
    console.error(`Release preparation failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
