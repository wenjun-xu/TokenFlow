"""Build a reproducible source release and its matching third-party tap formula."""

import argparse
import gzip
import hashlib
import io
import re
import tarfile
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def prepare(output, owner="wenjun-xu", repository="TokenFlow"):
    if not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?", owner):
        raise ValueError("Invalid GitHub owner")
    if not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.-]*", repository):
        raise ValueError("Invalid GitHub repository")
    with (ROOT / "pyproject.toml").open("rb") as stream:
        version = tomllib.load(stream)["project"]["version"]
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError("Release version must use major.minor.patch")
    name = f"tokenflow-{version}"
    sources = [ROOT / "pyproject.toml", ROOT / "README.md", Path(__file__)]
    for directory in ("tokenflow", "tests"):
        sources.extend(path for path in (ROOT / directory).rglob("*")
                       if path.suffix in {".py", ".js", ".html", ".css"})
    archive = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=archive, mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w") as bundle:
            for path in sorted(set(sources)):
                if path.is_symlink() or not path.is_file():
                    raise ValueError(f"Release source must be a regular file: {path.relative_to(ROOT)}")
                data = path.read_bytes()
                member = tarfile.TarInfo(f"{name}/{path.relative_to(ROOT).as_posix()}")
                member.size = len(data)
                member.mode = 0o644
                member.mtime = 0
                bundle.addfile(member, io.BytesIO(data))
    payload = archive.getvalue()
    checksum = hashlib.sha256(payload).hexdigest()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    (output / f"{name}.tar.gz").write_bytes(payload)
    (output / f"{name}.tar.gz.sha256").write_text(f"{checksum}  {name}.tar.gz\n", encoding="utf-8")
    formula = output / "homebrew-tap/Formula/tokenflow.rb"
    formula.parent.mkdir(parents=True, exist_ok=True)
    formula.write_text(f'''# Generated by scripts/prepare_release.py; publish the matching archive unchanged.
class Tokenflow < Formula
  desc "Local, read-only GitHub Copilot CLI token usage dashboard"
  homepage "https://github.com/{owner}/{repository}"
  url "https://github.com/{owner}/{repository}/releases/download/v{version}/{name}.tar.gz"
  sha256 "{checksum}"

  depends_on :macos
  depends_on "python@3.13"

  def install
    python = Formula["python@3.13"].opt_bin/"python3.13"
    system python, "-m", "venv", "--without-pip", libexec
    site_packages = Utils.safe_popen_read(
      libexec/"bin/python3", "-c", "import sysconfig; print(sysconfig.get_path('purelib'))"
    ).strip
    Pathname(site_packages).install "tokenflow"
    (bin/"tokenflow").write <<~PYTHON
      #!#{{libexec}}/bin/python3
      from tokenflow.cli import main
      raise SystemExit(main())
    PYTHON
    (bin/"tokenflow").chmod 0755
  end

  def caveats
    <<~EOS
      Run `tokenflow start` to open the local dashboard.
      Run `tokenflow stop` before upgrading or uninstalling.
      Requires working macOS sandbox-exec isolation; unsafe reads fail closed.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/tokenflow --version")
    system libexec/"bin/python3", "-c", <<~PYTHON
      from importlib.resources import files
      from pathlib import Path
      from tokenflow.cli import main
      from tokenflow.store import Metrics
      metrics = Metrics()
      metrics.add(dict(input_tokens=100, output_tokens=20, cache_read_tokens=80))
      assert metrics.result()["total_tokens"] == 120
      assert files("tokenflow").joinpath("web", "app.js").is_file()
      assert main(["start", "--db", "missing.db", "--no-browser"]) == 1
      assert not Path("missing.db").exists()
    PYTHON
  end
end
''', encoding="utf-8")
    return output / f"{name}.tar.gz", formula


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--owner", default="wenjun-xu")
    parser.add_argument("--repo", default="TokenFlow")
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    args = parser.parse_args()
    try:
        archive, formula = prepare(args.output, args.owner, args.repo)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"Release preparation failed: {error}\n")
    print(f"Source archive: {archive}")
    print(f"Tap formula: {formula}")
    print("Local files only. Upload the archive to the matching GitHub Release,")
    print("then copy Formula/tokenflow.rb into your homebrew-tap repository.")


if __name__ == "__main__":
    main()
